// defaultTestCommand is the packaged config's `github.test_command`.
const defaultTestCommand = "pytest"

var reBaseBranch = regexp.MustCompile(`(?m)^\s*base_branch:[ \t]*([^#\s]+)`)

// baseBranch is config.yaml's `dispatch.base_branch` as this scaffold wrote
// it, "" when it has none.
func (w *writer) baseBranch() string {
	raw, err := os.ReadFile(w.path(filepath.Join(".orchestrator", "config.yaml"))) // #nosec G304 -- the file this scaffold just wrote
	if err != nil {
		return ""
	}
	if m := reBaseBranch.FindSubmatch(raw); m != nil {
		return strings.Trim(string(m[1]), `"'`)
	}
	return ""
}

var reTestCommand = regexp.MustCompile(`(?m)^(\s*test_command:[ \t]*)([^#\n]*?)[ \t]*(#.*)?$`)

// testCommand is config.yaml's `github.test_command`, after replacing the
// packaged `pytest` with what the repo's own files imply: a template names
// its command on purpose, the packaged default only guesses. "" when the repo
// says nothing orch can read (#348) — config.yaml then says `""` too, and the
// workflow is a placeholder rather than Python.
func (w *writer) testCommand() string {
	rel := filepath.Join(".orchestrator", "config.yaml")
	raw, err := os.ReadFile(w.path(rel)) // #nosec G304 -- the file this scaffold just wrote
	if err != nil {
		return defaultTestCommand
	}
	m := reTestCommand.FindStringSubmatchIndex(string(raw))
	if m == nil {
		return defaultTestCommand
	}
	current := strings.TrimSpace(string(raw[m[4]:m[5]]))
	// A template's `pytest` is the template's stack, said before there is
	// code to say it (python-api on an empty repo); only the packaged
	// config's is a guess.
	if current != defaultTestCommand || w.project != nil {
		return current
	}
	detected := repoTestCommand(w.root)
	if detected == current {
		return current
	}
	value := detected
	if value == "" {
		value = `""`
	}
	w.write(rel, []byte(string(raw[:m[4]])+value+string(raw[m[5]:])), 0o600)
	return detected
}

// repoTestCommand guesses the test command from the files at the root, ""
// when they name no stack. It only runs when internal/ci found no check to
// run, so a node repo here has no `test` script at its root: the command
// must not need one.
func repoTestCommand(root string) string {
	switch {
	case exists(root, "go.mod"):
		return "go test ./..."
	case exists(root, "package.json"):
		return nodeTestCommand(root)
	case exists(root, "pubspec.yaml"):
		return "flutter analyze && flutter test"
	case exists(root, "pyproject.toml") || exists(root, "requirements.txt") || exists(root, "setup.py"):
		return defaultTestCommand
	}
	// Nothing to go on — most often a repository scaffolded before its code
	// exists. Python was the answer here until #348, and a pnpm monorepo
	// built later by the tasks failed CI on every PR.
	return ""
}

// nodeTestCommand is a node repo's test command. A root `check` script is
// the repo's own "verify everything"; otherwise every workspace member's
// `test`, where it has one (pnpm), or the root's if present (npm).
func nodeTestCommand(root string) string {
	manager := "npm"
	switch {
	case exists(root, "pnpm-lock.yaml"):
		manager = "pnpm"
	case exists(root, "yarn.lock"):
		manager = "yarn"
	}
	if hasScript(root, "check") {
		return manager + " run check"
	}
	switch manager {
	case "pnpm":
		return "pnpm -r --if-present test"
	case "yarn":
		return "yarn test"
	}
	return "npm run test --if-present"
}

// hasScript reports whether the root package.json declares the script. An
// unreadable package.json has none: the guess falls back, it does not fail
// `orch init`.
func hasScript(root, name string) bool {
	raw, err := os.ReadFile(filepath.Join(root, "package.json")) // #nosec G304 -- the repository being scaffolded
	if err != nil {
		return false
	}
	var pkg struct {
		Scripts map[string]string `json:"scripts"`
	}
	if json.Unmarshal(raw, &pkg) != nil {
		return false
	}
	_, ok := pkg.Scripts[name]
	return ok
}

// placeholderWorkflow is the workflow for a repo whose stack orch cannot
// tell (#348). It passes, so the auto-PR loop is not stuck on a red check
// nothing could make green, and it says what to do instead.
const placeholderWorkflow = `# Generated by ` + "`orch init`" + `. Safe to edit — orch never
# overwrites this file once it exists.
#
# orch could not tell this repository's stack when it was scaffolded (no
# go.mod, package.json, pubspec.yaml, pyproject.toml or requirements.txt),
# so this job runs nothing and passes. Replace the step below with the
# project's own checks, or run ` + "`orch ci setup`" + ` once the code exists to
# have them proposed.
name: orch-ci

on:
  pull_request:
  push:
    branches: [main]

` + ci.Concurrency + `
jobs:
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: ` + ci.PlaceholderStep + `
        run: echo "No test command yet. Edit .github/workflows/orch-ci.yml or run orch ci setup."
`

// setupSteps are the workflow steps that install the toolchain and the
// dependencies the test command needs, picked by the command's first word.
func setupSteps(root, testCommand string) string {
	const node = "      - uses: actions/setup-node@v4\n" +
		"        with:\n" +
		"          node-version: 22\n"
	fields := strings.Fields(testCommand)
	first := ""
	if len(fields) > 0 {
		first = fields[0]
	}
	switch first {
	case "flutter":
		return "      - uses: subosito/flutter-action@v2\n" +
			"        with:\n" +
			"          channel: stable\n" +
			"      - name: Install dependencies\n" +
			"        run: flutter pub get"
	case "go":
		return "      - uses: actions/setup-go@v5\n" +
			"        with:\n" +
			"          go-version-file: go.mod"
	case "pnpm":
		return node +
			"      - name: Install dependencies\n" +
			"        run: npm install -g pnpm && pnpm install --frozen-lockfile"
	case "yarn":
		return node +
			"      - name: Install dependencies\n" +
			"        run: yarn install --frozen-lockfile"
	case "npm", "npx", "node":
		install := "npm install"
		if exists(root, "package-lock.json") {
			install = "npm ci"
		}
		return node +
			"      - name: Install dependencies\n" +
			"        run: " + install
	}
	return "      - uses: actions/setup-python@v5\n" +
		"        with:\n" +
		"          python-version: \"3.11\"\n" +
		"      - name: Install dependencies\n" +
		"        run: pip install -e .[dev]"
}

func exists(root, name string) bool {
	_, err := os.Stat(filepath.Join(root, name))
	return err == nil
}
